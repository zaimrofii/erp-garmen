"""Export laporan H4 — Excel (.xlsx) & PDF (H4.8, modul 8/8 FASE H4).

``POST /api/v1/export/<report>/`` → **file binary** (``Content-Disposition:
attachment``). Satu endpoint melayani **7 laporan** H4:
``sales`` | ``purchases`` | ``stock`` | ``cogs`` | ``pnl`` | ``production`` |
``executive``.

Prinsip (keputusan H4.8):

* **ORKESTRASI, bukan duplikasi**: data diambil lewat helper internal H4.1–H4.7
  di `monitoring` (satu arah: ``export → monitoring``, jadi **tidak ada circular
  import**). Tidak ada rumus yang disalin — angka export = angka halaman laporan;
* **shim request** (`_QueryShim`): parser filter H4.x (`_sales_range`,
  `_sales_options`, …) menerima objek ber-``query_params`` → dipakai **apa adanya**
  sehingga validasi **400** (rentang/`group_by`/`product_id` tidak dikenal) identik
  dengan endpoint laporan, tanpa menulis ulang parsing;
* **tanpa cache laporan**: export selalu menghitung ulang (file = data saat itu);
  ``?_nocache`` diterima tetapi tidak berpengaruh;
* **fail-safe** (pola H4.7): stok Odoo tak terbaca → file **tetap dibuat** dengan
  tabel kosong + baris keterangan, bukan error 500;
* template: **Excel** = sheet ``Summary`` (judul + periode + KPI) + sheet ``Data``
  (header beku + lebar kolom otomatis); khusus dashboard eksekutif = **7 sheet**
  (satu per section: sales/purchases/stock/cogs/pnl/production/alerts);
  **PDF** = A4 **landscape** untuk 6 laporan tabel, A4 **portrait** untuk
  dashboard eksekutif (KPI), footer ``Generated by MES — Page N``.

Read-only (tanpa Odoo write/task/migration) dan **tidak** mengubah B2 maupun
H4.1–H4.7. Izin ``IsAuthenticated`` → anonim **403**.
"""

