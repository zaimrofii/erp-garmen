class _QueryShim:
    """Request tiruan: hanya ``.query_params`` yang dibaca parser H4.1–H4.7."""

    def __init__(self, params: dict) -> None:
        """Simpan mapping param (gabungan query string + body JSON)."""
        self.query_params = params


def _export_params(request) -> dict:
    """Gabung ``?query`` + body JSON → ``{str: str}`` (**body menang**).

    Nilai non-string (mis. ``{"format": "pdf", "group_by": "vendor"}`` sudah string,
    tetapi ``{"nocache": true}`` boolean) dinormalkan ke bentuk yang dipahami parser
    H4.x (``"1"``/``"0"``) supaya shim bisa dipakai apa adanya.
    """
    params: dict = {}
    for key, value in request.query_params.items():
        params[str(key)] = value

    data = request.data
    if isinstance(data, dict):
        for key, value in data.items():
            if value is None:
                continue
            if value is True:
                params[str(key)] = "1"
            elif value is False:
                params[str(key)] = "0"
            else:
                params[str(key)] = value if isinstance(value, str) else str(value)

    return {key: str(value) for key, value in params.items()}


def _export_format(params: dict) -> str:
    """Format file dari ``body.format`` → ``?format=`` → default (lowercase)."""
    raw = str(params.get("format") or "").strip().lower()
    return raw or EXPORT_DEFAULT_FORMAT


def _export_period_label(from_dt, to_dt, requested: str) -> str:
    """Label periode untuk nama file/header — **PURE**.

    Prioritas: ``?period`` yang diminta klien → tepat **1 bulan** (``YYYY-MM``) →
    tepat **1 kuartal** (``YYYY-Qn``) → rentang bebas (``YYYYMMDD-YYYYMMDD``).
    """
    if requested:
        return requested

    start = timezone.localtime(from_dt).date()
    end = timezone.localtime(to_dt).date()
    last_day = monthrange(end.year, end.month)[1]

    if start.day == 1 and end.year == start.year and end.month == start.month:
        if end.day == last_day:
            return start.strftime("%Y-%m")

    if (
        start.day == 1
        and start.year == end.year
        and start.month in (1, 4, 7, 10)
        and end.month - start.month == 2
        and end.day == last_day
    ):
        return f"{start.year}-Q{(start.month - 1) // 3 + 1}"

    return f"{start.strftime('%Y%m%d')}-{end.strftime('%Y%m%d')}"


def _export_filename(report: str, dataset: dict, fmt: str) -> str:
    """``<report>-<periode|range>.<ext>`` (snapshot stok → tanggal hari ini)."""
    label = str(dataset.get("file_label") or "snapshot")
    return f"{report}-{label}.{fmt}"


