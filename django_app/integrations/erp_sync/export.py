def _pdf_footer(canvas, doc) -> None:
    """Footer setiap halaman: ``Generated by MES`` + nomor halaman."""
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#6B7280"))
    canvas.drawString(12 * mm, 9 * mm, "Generated by MES")
    canvas.drawRightString(doc.pagesize[0] - 12 * mm, 9 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _pdf_kpi_table(kpis) -> Table:
    """Tabel KPI **4 kolom** (label|nilai|label|nilai) supaya ringkas."""
    rows: list = []
    current: list = []
    for label, value, kind in kpis:
        current.extend([str(label), _cell_text(value, kind)])
        if len(current) == 4:
            rows.append(current)
            current = []
    if current:
        while len(current) < 4:
            current.append("")
        rows.append(current)

    table = Table(rows, colWidths=[42 * mm, 34 * mm, 42 * mm, 34 * mm])
    table.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#D1D5DB")),
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F9FAFB")),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
            ]
        )
    )
    return table


def _pdf_data_table(headers, rows, kinds: tuple = ()) -> Table:
    """Tabel data bergaris + header berulang tiap halaman (``repeatRows=1``).

    ``kinds`` kosong → ``rows`` **sudah** berupa teks siap tampil (dipakai section
    dashboard eksekutif yang kind-nya beda per baris).
    """
    if kinds:
        body_rows = [
            [_cell_text(value, kind) for value, kind in zip(row, kinds)] for row in rows
        ]
    else:
        body_rows = [list(row) for row in rows]
    body = [list(headers)] + body_rows
    if len(body) == 1:
        body.append(["(tidak ada baris pada filter ini)"] + [""] * (len(headers) - 1))

    table = Table(body, repeatRows=1)
    style: list = [
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#9CA3AF")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E5E7EB")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 7),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]
    for index, kind in enumerate(kinds, start=0):
        style.append(
            ("ALIGN", (index, 0), (index, -1), "LEFT" if kind == "text" else "RIGHT")
        )
    table.setStyle(TableStyle(style))
    return table


def _export_to_pdf(dataset: dict) -> io.BytesIO:
    """Bangun berkas ``.pdf`` (A4 landscape untuk 6 laporan tabel; portrait eksekutif)."""
    buffer = io.BytesIO()
    landscape_mode = dataset["report"] in EXPORT_LANDSCAPE_REPORTS
    page_size = landscape(A4) if landscape_mode else A4

    document = SimpleDocTemplate(
        buffer,
        pagesize=page_size,
        leftMargin=12 * mm,
        rightMargin=12 * mm,
        topMargin=12 * mm,
        bottomMargin=16 * mm,
        title=dataset["title"],
        author="MES",
        subject=f"Export {dataset['report']} {dataset['period_label']}",
    )

    styles = _pdf_styles()
    story: list = [
        Paragraph(dataset["title"], styles["title"]),
        Paragraph(f"Periode: {dataset['period_label']}", styles["meta"]),
        Paragraph(
            f"Dibuat: {dataset['generated_at']} — MES (read-only, tanpa tabel stok di MES)",
            styles["meta"],
        ),
    ]
    for note in dataset["notes"]:
        story.append(Paragraph(str(note), styles["meta"]))
    story.append(Spacer(1, 6))
    story.append(Paragraph("Ringkasan KPI", styles["section"]))
    story.append(_pdf_kpi_table(dataset["kpis"]))

    if dataset["report"] == "executive":
        for section in dataset["sections"]:
            story.append(PageBreak())
            story.append(Paragraph(section["title"], styles["section"]))
            rows = [
                (entry[0], _cell_text(entry[1], entry[2])) for entry in section["rows"]
            ]
            story.append(_pdf_data_table(section["headers"], rows))
    else:
        story.append(Paragraph("Data", styles["section"]))
        kinds = tuple(column[2] for column in dataset["columns"])
        headers = [column[0] for column in dataset["columns"]]
        rows = [
            tuple(item.get(column[1]) for column in dataset["columns"])
            for item in dataset["rows"]
        ]
        story.append(_pdf_data_table(headers, rows, kinds))

    document.build(story, onFirstPage=_pdf_footer, onLaterPages=_pdf_footer)
    buffer.seek(0)
    return buffer


class ExportReportView(APIView):
    """``POST /api/v1/export/<report>/`` — unduh laporan H4 sebagai Excel/PDF (H4.8).

    Body JSON (semua opsional) memakai **param yang sama** dengan endpoint laporan
    H4.x — ``?period``/``?date_from``/``?date_to``/``?from``/``?to``,
    ``?group_by``, filter spesifik laporan (``customer_id``/``vendor_id``/
    ``product_id``/``order_type``/``status``/``location_id``/``search``/
    ``only_nonzero``/``work_center_id``/``line_id``) + ``format``:

        {"period": "2026-10", "group_by": "product", "format": "pdf"}

    * ``format`` juga boleh lewat query string (``?format=pdf``); **body menang**.
      Default ``xlsx``; nilai lain → **400**;
    * ``report`` di luar `EXPORT_REPORTS` → **404**; rentang/filter tidak valid →
      **400** dengan pesan yang sama seperti endpoint laporan (reuse parser H4.x);
    * respons = **file binary**: ``Content-Type`` per format +
      ``Content-Disposition: attachment; filename="<report>-<periode>.<ext>"``
      (snapshot stok → ``stock-<YYYYMMDD>``);
    * **tanpa cache**: setiap export menghitung ulang datanya (file = data saat itu);
      ``?_nocache`` diterima tetapi tidak berpengaruh;
    * fail-safe stok (pola H4.7): Odoo tak terbaca → file tetap dibuat (tabel kosong
      + keterangan), **bukan** 500.

    Read-only (tanpa Odoo write/Celery/migration) dan tidak mengubah B2 maupun
    H4.1–H4.7. Anonim **403**.
    """

    permission_classes = [IsAuthenticated]

    def perform_content_negotiation(self, request, force=False):
        """Lewati negosiasi format DRF agar ``?format=`` bebas dipakai H4.8.

        DRF memakai query param ``format`` (`FORMAT_QUERY_PARAM`) untuk memilih
        *renderer*; kalau nilainya ``xlsx``/``pdf`` (bukan renderer terdaftar) DRF
        membalas **404 sebelum view jalan**. Endpoint H4.8 memakai param itu sebagai
        **format berkas**, jadi negosiasi dilewati (respons sukses = `HttpResponse`
        binary; respons error tetap JSON).
        """
        return JSONRenderer(), "application/json"

    def post(self, request, report):  # noqa: ARG002 - request dipakai lewat helper
        """Bangun & kirim berkas export; lihat docstring kelas."""
        report_key = str(report or "").strip().lower()
        if report_key not in EXPORT_REPORTS:
            return Response(
                {"detail": f"Laporan {report_key!r} tidak dikenal."},
                status=status.HTTP_404_NOT_FOUND,
            )

        params = _export_params(request)
        export_format = _export_format(params)
        if export_format not in EXPORT_FORMATS:
            return Response(
                {"detail": f"Parameter 'format'={export_format!r} harus xlsx|pdf."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        try:
            dataset = _export_dataset(report_key, _QueryShim(params))
        except _ExportError as exc:
            return Response({"detail": str(exc)}, status=status.HTTP_400_BAD_REQUEST)

        buffer = (
            _export_to_xlsx(dataset) if export_format == "xlsx" else _export_to_pdf(dataset)
        )
        filename = _export_filename(report_key, dataset, export_format)
        response = HttpResponse(buffer.getvalue(), content_type=EXPORT_MIME[export_format])
        response["Content-Disposition"] = f'attachment; filename="{filename}"'
        response["X-Export-Report"] = report_key
        response["X-Export-Format"] = export_format

        logger.info(
            "export report: report=%s format=%s period=%s rows=%s bytes=%s",
            report_key,
            export_format,
            dataset["period_label"],
            len(dataset["rows"]),
            len(buffer.getvalue()),
        )
        return response
