def _cell_text(value, kind: str) -> str:
    """PURE — nilai sel → teks (PDF); ``None`` → ``-`` (tidak dikarang 0)."""
    if value is None or value == "":
        return "-"
    if kind == "money":
        return f"Rp{float(value):,.0f}".replace(",", ".")
    if kind == "pct":
        return f"{float(value):,.2f}%".replace(",", ".")
    if kind == "int":
        return f"{int(value):,}".replace(",", ".")
    if kind == "qty":
        text = f"{float(value):,.2f}".replace(",", ".")
        return text.rstrip("0").rstrip(".") or "0"
    return str(value)


def _xlsx_value(value, kind: str):
    """PURE — nilai sel Excel: angka tetap angka (bisa di-sum), ``None`` → ``-``."""
    if value is None or value == "":
        return "-"
    if kind in ("money", "qty", "pct", "int"):
        return value
    return str(value)


def _xlsx_sheet_name(title: str) -> str:
    """PURE — nama sheet aman (buang karakter terlarang Excel, maks 31 char)."""
    safe = title
    for char in ("\\", "/", "*", "?", ":", "[", "]"):
        safe = safe.replace(char, "-")
    return safe[:31]


def _xlsx_title_block(worksheet, dataset: dict, title: str) -> int:
    """Tulis blok judul (merged) + periode + catatan → baris awal tabel berikutnya."""
    worksheet["A1"] = title
    worksheet["A1"].font = Font(bold=True, size=14)
    worksheet.merge_cells(start_row=1, start_column=1, end_row=1, end_column=4)
    worksheet["A2"] = f"Periode: {dataset['period_label']}"
    worksheet["A3"] = f"Dibuat: {dataset['generated_at']} (MES read-only)"
    row = 4
    for note in dataset["notes"]:
        worksheet.cell(row=row, column=1, value=note)
        row += 1
    return row + 1


def _xlsx_table(worksheet, start_row: int, headers, rows) -> int:
    """Tulis tabel (header tebal + isian baris) → baris terakhir + 1."""
    for column, header in enumerate(headers, start=1):
        cell = worksheet.cell(row=start_row, column=column, value=header)
        cell.font = Font(bold=True)
        cell.fill = PatternFill("solid", fgColor="E5E7EB")
        cell.alignment = Alignment(horizontal="center", vertical="center")

    row = start_row + 1
    for entry in rows:
        if not isinstance(entry, (list, tuple)):
            entry = (entry,)
        for column, value in enumerate(entry, start=1):
            worksheet.cell(row=row, column=column, value=value)
        row += 1
    return row


def _xlsx_autosize(worksheet, max_row: int, max_column: int) -> None:
    """Lebar kolom auto-fit (dibatasi `_EXPORT_MAX_COL_WIDTH` supaya tetap rapi)."""
    for column in range(1, max_column + 1):
        longest = 0
        for row in range(1, max_row + 1):
            value = worksheet.cell(row=row, column=column).value
            if value is None:
                continue
            longest = max(longest, len(str(value)))
        width = min(longest + 2, _EXPORT_MAX_COL_WIDTH)
        worksheet.column_dimensions[get_column_letter(column)].width = max(width, 10)


def _xlsx_report_sheets(workbook: Workbook, dataset: dict) -> None:
    """Template 6 laporan tabel: sheet ``Summary`` (KPI) + ``Data`` (baris)."""
    summary = workbook.active
    summary.title = "Summary"
    row = _xlsx_title_block(summary, dataset, dataset["title"])
    row = _xlsx_table(
        summary,
        row,
        ("KPI", "Nilai"),
        [(label, _xlsx_value(value, kind)) for label, value, kind in dataset["kpis"]],
    )
    _xlsx_autosize(summary, row, 2)

    data = workbook.create_sheet("Data")
    headers = [column[0] for column in dataset["columns"]]
    summary_row = _xlsx_title_block(data, dataset, f"{dataset['title']} — Data")
    summary_row = _xlsx_table(
        data,
        summary_row,
        headers,
        [
            [_xlsx_value(item.get(key), kind) for _label, key, kind in dataset["columns"]]
            for item in dataset["rows"]
        ],
    )
    if len(dataset["rows"]) == 0:
        data.cell(row=summary_row, column=1, value="(tidak ada baris pada filter ini)")
        summary_row += 1
    data.freeze_panes = data.cell(row=5 + len(dataset["notes"]) + 1, column=1)
    _xlsx_autosize(data, summary_row, max(len(headers), 1))


def _xlsx_executive_sheets(workbook: Workbook, dataset: dict) -> None:
    """Template dashboard eksekutif: **7 sheet** — satu per section (keputusan H4.8)."""
    for index, section in enumerate(dataset["sections"]):
        if index == 0:
            worksheet = workbook.active
            worksheet.title = _xlsx_sheet_name(section["title"])
        else:
            worksheet = workbook.create_sheet(_xlsx_sheet_name(section["title"]))

        row = _xlsx_title_block(worksheet, dataset, f"{dataset['title']} — {section['title']}")
        row = _xlsx_table(
            worksheet,
            row,
            section["headers"],
            [(entry[0], _xlsx_value(entry[1], entry[2])) for entry in section["rows"]],
        )
        _xlsx_autosize(worksheet, row, len(section["headers"]))


def _export_to_xlsx(dataset: dict) -> io.BytesIO:
    """Bangun berkas ``.xlsx`` dari dataset (2 sheet, atau 7 sheet executive)."""
    workbook = Workbook()
    if dataset["report"] == "executive":
        _xlsx_executive_sheets(workbook, dataset)
    else:
        _xlsx_report_sheets(workbook, dataset)

    buffer = io.BytesIO()
    workbook.save(buffer)
    buffer.seek(0)
    return buffer


