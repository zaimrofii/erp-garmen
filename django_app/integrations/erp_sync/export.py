def _dataset_stock(shim) -> dict:
    """Dataset laporan stok (snapshot Odoo) — komposisi helper H4.3 + fail-safe."""
    options, error = mon._stock_options(shim)
    if error:
        raise _ExportError(error)

    location_odoo_id = None
    if options["location_id"] is not None:
        _location, location_odoo_id, error = mon._stock_location_filter(options["location_id"])
        if error:
            raise _ExportError(error)

    product_odoo_id = None
    if options["product_id"] is not None:
        product = Product.objects.filter(pk=options["product_id"]).first()
        if product is None:
            raise _ExportError(f"Product {options['product_id']} tidak ditemukan.")
        if not product.odoo_id:
            raise _ExportError(
                f"Product {product.code} belum punya odoo_id (belum tersinkron dari Odoo)."
            )
        product_odoo_id = int(product.odoo_id)
    options = {**options, "product_odoo_id": product_odoo_id}

    locations, quants, fetch_error = mon._stock_fetch(location_odoo_id)
    notes: list[str] = []
    if fetch_error is not None:
        # Fail-safe H4.8: file TETAP dibuat (tabel kosong + keterangan), bukan 500.
        by_product: dict = {}
        by_location: dict = {}
        location_meta: dict = {}
        products: dict = {}
        stats = {"quant_count": 0, "unmapped_product_count": 0, "unmapped_qty": 0.0}
        notes.append(EXPORT_STOCK_UNREADABLE)
    else:
        products = mon._stock_product_map()
        location_meta = mon._stock_location_meta(quants, locations, mon._stock_location_map())
        by_product, by_location, stats = mon._stock_aggregate(quants, products, options)
        if options["only_nonzero"]:
            by_product = {
                key: value for key, value in by_product.items() if mon._qty(value["qty"]) != 0
            }
            by_location = {
                key: value for key, value in by_location.items() if mon._qty(value["qty"]) != 0
            }

    summary = mon._stock_summary(by_product, by_location, stats)
    today: date = timezone.localtime(timezone.now()).date()

    return _dataset(
        "stock",
        rows=mon._stock_rows(by_product, by_location, products, location_meta, options["group_by"]),
        columns=_STOCK_COLUMNS,
        group_by=options["group_by"],
        period_label=f"snapshot {today.isoformat()}",
        file_label=today.strftime("%Y%m%d"),
        kpis=(
            ("Total Qty", summary["total_qty"], "qty"),
            ("Available", summary["available_qty"], "qty"),
            ("Reserved", summary["reserved_qty"], "qty"),
            ("Jumlah Produk", summary["product_count"], "int"),
            ("Jumlah Lokasi", summary["location_count"], "int"),
            ("Quant", summary["quant_count"], "int"),
            ("Produk tanpa odoo_id", summary["unmapped_product_count"], "int"),
            ("Qty tanpa master", summary["unmapped_qty"], "qty"),
        ),
        notes=notes
        + [
            f"group_by={options['group_by']}",
            "Sumber: snapshot Odoo stock.quant (read-only, tanpa tabel stok di MES)",
        ],
    )


